func jpegSegment(marker byte, payload []byte) []byte {
	out := []byte{0xFF, marker, 0, 0}
	binary.BigEndian.PutUint16(out[2:4], uint16(len(payload)+2))
	return append(out, payload...)
}

// buildJPEG assembles SOI + the given metadata segments + a minimal scan + EOI.
func buildJPEG(segments ...[]byte) []byte {
	out := []byte{0xFF, 0xD8}
	for _, s := range segments {
		out = append(out, s...)
	}
	out = append(out, jpegSegment(0xDA, []byte{0x01, 0x01, 0x00})...) // SOS
	out = append(out, 0x12, 0x34, 0x56, 0x78)                         // "compressed" scan
	out = append(out, 0xFF, 0xD9)                                     // EOI
	return out
}

func pngChunk(kind string, payload []byte) []byte {
	out := make([]byte, 4)
	binary.BigEndian.PutUint32(out, uint32(len(payload)))
	out = append(out, kind...)
	out = append(out, payload...)
	return append(out, 0, 0, 0, 0) // CRC: never verified, never rewritten
}

func buildPNG(chunks ...[]byte) []byte {
	out := []byte("\x89PNG\r\n\x1a\n")
	out = append(out, pngChunk("IHDR", make([]byte, 13))...)
	for _, c := range chunks {
		out = append(out, c...)
	}
	out = append(out, pngChunk("IDAT", []byte{0x78, 0x9c, 0x03, 0x00})...)
	return append(out, pngChunk("IEND", nil)...)
}

func webpChunk(kind string, payload []byte) []byte {
	out := append([]byte(kind), 0, 0, 0, 0)
	binary.LittleEndian.PutUint32(out[4:8], uint32(len(payload)))
	out = append(out, payload...)
	if len(payload)%2 == 1 {
		out = append(out, 0)
	}
	return out
}

func buildWebP(chunks ...[]byte) []byte {
	body := webpChunk("VP8 ", []byte{1, 2, 3, 4})
	for _, c := range chunks {
		body = append(body, c...)
	}
	out := append([]byte("RIFF"), 0, 0, 0, 0)
	out = append(out, "WEBP"...)
	out = append(out, body...)
	binary.LittleEndian.PutUint32(out[4:8], uint32(len(out)-8))
	return out
}

const xmpHeader = "http://ns.adobe.com/xap/1.0/\x00"

